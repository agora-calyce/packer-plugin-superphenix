package postprocessor

import (
	"context"
	"fmt"
	"io"
	"net"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"sync/atomic"
	"time"

	packersdk "github.com/hashicorp/packer-plugin-sdk/packer"
	"golang.org/x/crypto/ssh"
)

type transferFunc func(ctx context.Context, ui packersdk.Ui, host, user string, signer ssh.Signer, hostKey ssh.PublicKey, dev, out string) error

const (
	remoteOut    = "/var/tmp/out.qcow2"
	stallTimeout = 60 * time.Second // no byte received within this delay: the connection is cut and the transfer resumed
	maxResumes   = 20
)

// detectDisk lists the helper's disks excluding root, loop, cdrom and cloud-init (cidata label).
const detectDisk = `root=$(lsblk -ndo PKNAME "$(findmnt -no SOURCE /)"); for d in $(lsblk -dnpo NAME -e 7,11); do ` +
	`[ "${d#/dev/}" = "$root" ] && continue; [ "$(sudo blkid -s LABEL -o value $d 2>/dev/null)" = cidata ] && continue; echo $d; done`

// progress records the time of the last byte received, to detect a stalled transfer.
type progress struct {
	w    io.Writer
	last atomic.Int64
}

func (p *progress) Write(b []byte) (int, error) {
	p.last.Store(time.Now().UnixNano())
	return p.w.Write(b)
}

// localWriter remembers the first local write error (disk full, permissions...): it has nothing to do
// with the network, so resuming the download would be pointless.
type localWriter struct {
	w   io.Writer
	err error
}

func (l *localWriter) Write(b []byte) (int, error) {
	n, err := l.w.Write(b)
	if err != nil && l.err == nil {
		l.err = err
	}
	return n, err
}

// pull copies remoteOut from offset off to w. A stalled connection is closed by a watchdog.
func pull(cli *ssh.Client, w io.Writer, off int64) error {
	s, err := cli.NewSession()
	if err != nil {
		return err
	}
	defer s.Close()
	pw := &progress{w: w}
	pw.last.Store(time.Now().UnixNano())
	s.Stdout = pw
	done := make(chan struct{})
	defer close(done)
	go func() {
		t := time.NewTicker(5 * time.Second)
		defer t.Stop()
		for {
			select {
			case <-done:
				return
			case <-t.C:
				if time.Since(time.Unix(0, pw.last.Load())) > stallTimeout {
					cli.Close()
					return
				}
			}
		}
	}()
	return s.Run(fmt.Sprintf("tail -c +%d %s", off+1, remoteOut))
}

// sshFetch: waits for cloud-init, converts dev to qcow2 on the helper, then downloads the file through SSH stdout (with resume).
func sshFetch(ctx context.Context, ui packersdk.Ui, host, user string, signer ssh.Signer, hostKey ssh.PublicKey, dev, out string) (err error) {
	cfg := &ssh.ClientConfig{User: user, Auth: []ssh.AuthMethod{ssh.PublicKeys(signer)}, Timeout: 15 * time.Second,
		// The helper's host key is generated by the plugin and injected through cloud-init (helperHostKey): only that
		// key is accepted. Until cloud-init has installed it the dial fails on a mismatch and connect retries.
		HostKeyCallback: ssh.FixedHostKey(hostKey), HostKeyAlgorithms: []string{hostKey.Type()}}
	connect := func() (*ssh.Client, error) {
		deadline := time.Now().Add(10 * time.Minute)
		for {
			cli, err := ssh.Dial("tcp", net.JoinHostPort(host, "22"), cfg)
			if err == nil {
				return cli, nil
			}
			if time.Now().After(deadline) || ctx.Err() != nil {
				return nil, fmt.Errorf("ssh to helper %s: %w (Packer must run inside the subnet or behind a VPN to reach the helper's private IP)", host, err)
			}
			time.Sleep(5 * time.Second)
		}
	}
	cli, err := connect()
	if err != nil {
		return err
	}
	// Ctrl-C: closing the current connection interrupts ongoing sessions and download. AfterFunc fires once, so a
	// connection opened by a resume after the cancellation is closed by the ctx check below.
	var cur atomic.Pointer[ssh.Client]
	cur.Store(cli)
	stop := context.AfterFunc(ctx, func() { cur.Load().Close() })
	defer stop()
	defer func() { cur.Load().Close() }()

	run := func(cmd string) ([]byte, error) {
		s, err := cli.NewSession()
		if err != nil {
			return nil, err
		}
		defer s.Close()
		o, err := s.CombinedOutput(cmd)
		if err != nil {
			return o, fmt.Errorf("%q: %w: %s", cmd, err, o)
		}
		return o, nil
	}
	// cloud-init installs qemu-utils; --wait blocks until it finishes.
	if _, err := run("sudo cloud-init status --wait; command -v qemu-img"); err != nil {
		return err
	}
	if dev == "" {
		// Disk order is not guaranteed: pick the one that is neither the helper's root nor the cloud-init disk.
		o, err := run(detectDisk)
		if err != nil {
			return err
		}
		if disks := strings.Fields(string(o)); len(disks) == 1 {
			dev = disks[0]
		} else {
			return fmt.Errorf("cannot detect the exported disk (candidates: %q); set disk_device", disks)
		}
		ui.Say("Exported disk detected: " + dev)
	}
	if _, err := run(fmt.Sprintf("sudo qemu-img convert -f raw -O qcow2 %s %s", dev, remoteOut)); err != nil {
		// Diagnostic: helper's disk layout and free space (helps choosing disk_device).
		if o, _ := run("lsblk -o NAME,SIZE,TYPE,FSTYPE,LABEL,MOUNTPOINT; df -h /var/tmp"); len(o) > 0 {
			err = fmt.Errorf("%w\nhelper disks:\n%s", err, o)
		}
		return err
	}
	sz, err := run("stat -c %s " + remoteOut)
	if err != nil {
		return err
	}
	size, err := strconv.ParseInt(strings.TrimSpace(string(sz)), 10, 64)
	if err != nil {
		return fmt.Errorf("remote size %q: %w", sz, err)
	}
	// Fail fast: do not download gigabytes to a disk that cannot hold them.
	if free, ferr := freeBytes(filepath.Dir(out)); ferr == nil && uint64(size) > free {
		return fmt.Errorf("not enough free space for %s: the qcow2 is %d bytes, only %d are free in %s (free some space or point output_path to a larger volume)",
			out, size, free, filepath.Dir(out))
	}

	// Download to a temporary file renamed on success: a failed run never destroys a previous qcow2 at out.
	tmp := out + ".part"
	f, err := os.Create(tmp)
	if err != nil {
		return err
	}
	defer func() {
		f.Close()
		if err != nil {
			os.Remove(tmp) // no partial qcow2
		}
	}()
	lw := &localWriter{w: f}
	var got int64
	for resumes := 0; got < size; resumes++ {
		if resumes > maxResumes {
			return fmt.Errorf("download qcow2: gave up after %d resumes at %d/%d bytes", maxResumes, got, size)
		}
		if resumes > 0 {
			ui.Say(fmt.Sprintf("Download stalled at %d/%d bytes, resuming...", got, size))
			cli.Close()
			// Temporary variable: on failure cli must stay non-nil for the deferred Close and the Ctrl-C hook.
			nc, cerr := connect()
			if cerr != nil {
				return cerr
			}
			cli = nc
			cur.Store(nc)
			if ctx.Err() != nil {
				nc.Close()
				return fmt.Errorf("download qcow2: %w", ctx.Err())
			}
		}
		perr := pull(cli, lw, got)
		if lw.err != nil {
			return fmt.Errorf("write %s: %w", out, lw.err)
		}
		if got, err = f.Seek(0, io.SeekEnd); err != nil {
			return err
		}
		if ctx.Err() != nil {
			return fmt.Errorf("download qcow2: %w", ctx.Err())
		}
		if perr != nil && got < size {
			continue
		}
	}
	if err = f.Close(); err != nil {
		return err
	}
	os.Remove(out) // Windows cannot rename over an existing file; -force was checked in Configure
	return os.Rename(tmp, out)
}
