# common/scripts/windows/windows-cleanup.ps1
# Cleans temporary files and Windows Update leftovers before export.

$servicesToRecycle = "wuauserv", "cryptSvc", "bits", "msiserver"
$tempFoldersToClear = @(
    "C:\Windows\Temp",
    "C:\Users\*\AppData\Local\Temp",
    "C:\Windows\SoftwareDistribution\Download",
    "C:\Windows\SoftwareDistribution\DataStore\Logs",
    "C:\Windows\Panther"
)

Stop-Service -Name $servicesToRecycle -Force -ErrorAction SilentlyContinue

# -Exclude packer-*: Packer drops its own orchestration files (env-vars,
# wrapper) in C:\Windows\Temp during the running elevated execution;
# deleting them blindly breaks the current step.
foreach ($folder in $tempFoldersToClear) {
    Get-ChildItem $folder -Recurse -Force -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -notlike 'packer-*' } |
        Remove-Item -Force -Recurse -ErrorAction SilentlyContinue
}

# File generated by the package-list provisioner (already downloaded to
# the host at this point, no need to keep it in the image).
Remove-Item -Path "C:\packages.csv" -Force -ErrorAction SilentlyContinue

Start-Service -Name $servicesToRecycle -ErrorAction SilentlyContinue

# autounattend.xml disables the firewall during install (EnableFirewall
# false) to simplify the build. Nothing re-enabled it afterwards -> the
# final image shipped with the firewall permanently disabled.
Set-NetFirewallProfile -All -Enabled True
